import asyncio
from playwright.async_api import async_playwright
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); ctx=await b.new_context(accept_downloads=True, viewport={'width':1300,'height':900})
    pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('console',lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
    await pg.goto('file:///home/claude/hd/build/index.html')
    href=await pg.get_attribute('#bm','href'); print('bm href', href[:40], len(href))
    await pg.screenshot(path='a1.png', full_page=True)
    await pg.click('#t2')
    await pg.set_input_files('#f2','out.zip')
    await pg.wait_for_selector('#out2:not([hidden])', timeout=60000)
    print('kpis:', (await pg.inner_text('#kpis')).replace('\n',' | '))
    print('warns:', (await pg.inner_text('#warns'))[:600])
    print('mst:', await pg.input_value('#mymst'))
    await pg.screenshot(path='a2.png', full_page=True)
    async with pg.expect_download() as dl: await pg.click('#bxls')
    d=await dl.value; await d.save_as('a2.xlsx'); print('xlsx', d.suggested_filename)
    await pg.click('#t3')
    await pg.set_input_files('#f3','small_goc.zip')
    await pg.wait_for_timeout(2500)
    print('t3:', await pg.inner_text('#n3'))
    await pg.screenshot(path='a3.png', full_page=True)
    async with ctx.expect_page() as np: await pg.click('#bprint')
    w=await np.value; await w.wait_for_timeout(3000)
    print('print win:', await w.evaluate('[document.querySelectorAll(".qtt-inv").length, document.querySelectorAll(".qtt-inv img").length, document.querySelectorAll("script").length]'))
    await w.screenshot(path='a4.png', full_page=True)
    print('errs', errs); await b.close()
asyncio.run(main())
